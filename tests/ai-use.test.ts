import test from 'node:test';
import assert from 'node:assert/strict';
import type { WorkerInfo } from '../src/shared/protocol.js';
import { agentLabel, aiUseBlock, withAiUse } from '../src/server/workers/ai-use.js';
import type { PromptSource } from '../src/server/prompts.js';
import { PROMPTS, type PromptId } from '../src/shared/prompts.js';

const worker = (over: Partial<WorkerInfo> = {}) => ({ id: 'w1', name: 'Mochi', deskId: 'd1', provider: 'claude', ...over }) as WorkerInfo;
const rewritten = (text: string): PromptSource => ({ text: (id: PromptId) => (id === 'pull.aiUse' ? text : PROMPTS[id].text) }) as PromptSource;

test('names the agent, with the model its session ran on before the one it was asked for', () => {
  assert.equal(agentLabel(worker()), 'Claude Code');
  assert.equal(agentLabel(worker({ model: 'opus' })), 'Claude Code (opus)');
  assert.equal(agentLabel(worker({ model: 'opus', usage: { model: 'claude-opus-5-5' } as WorkerInfo['usage'] })), 'Claude Code (claude-opus-5-5)');
  assert.equal(agentLabel(worker({ provider: 'codex' })), 'Codex');
  // A plain shell is a person typing: there's no AI to name.
  assert.equal(agentLabel(worker({ kind: 'shell' })), undefined);
});

test('the section says who wrote it and leaves how it was verified to the reviewer', () => {
  const block = aiUseBlock(worker({ model: 'opus' }));
  assert.match(block, /^<!-- agent-office:ai-use -->\n## AI use\n/);
  assert.match(block, /\*\*Generated by:\*\* Claude Code \(opus\), as Mochi in Agent Office/);
  assert.match(block, /\*\*Verified by:\*\*/);
  assert.match(block, /<!-- \/agent-office:ai-use -->$/);
  assert.equal(aiUseBlock(worker({ kind: 'shell' })), '');
});

test('⚙️ Settings can reword it, or empty it to add nothing', () => {
  assert.match(aiUseBlock(worker(), rewritten('AI: {{agent}}. Tax cases checked by hand: [ ]')), /AI: Claude Code\. Tax cases checked by hand: \[ \]/);
  assert.equal(aiUseBlock(worker(), rewritten('')), '');
});

test('the section is added once and never rewritten, so what the reviewer filled in stays', () => {
  const block = aiUseBlock(worker());
  const once = withAiUse('## Summary\n\nFixes it\n', block);
  assert.equal(once, `## Summary\n\nFixes it\n\n${block}`);
  const filled = once.replace('_who read, tested and understood it, and how_', 'JP: read it, ran npm test');
  assert.equal(withAiUse(filled, aiUseBlock(worker({ model: 'opus' }))), filled);
  assert.equal(withAiUse('', block), block);
  assert.equal(withAiUse('body', ''), 'body');
});
